import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtemp, mkdir, readFile, writeFile, rm, realpath } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, isAbsolute } from 'node:path';
import { BridgeError } from './errors.js';
import { CODEX_VERSION, executablePath, RpcProcess } from './process.js';

const exec = promisify(execFile);
const lockUrl = new URL('../assets/codex-0.144.6.lock.toml', import.meta.url);
export async function prepareRuntime(credentialStore = 'file') {
  if (!['file', 'keyring'].includes(credentialStore)) throw new BridgeError('CONFIG_INVALID');
  const root = await mkdtemp(join(tmpdir(), 'dsh-codex-subscription-'));
  try {
    for (const name of ['home', 'auth-probe', 'cwd', 'state', 'logs']) await mkdir(join(root, name), { mode: 0o700 });
    const template = await readFile(lockUrl, 'utf8');
    // Only a path generated by mkdtemp enters the immutable template.
    const escapedRoot = JSON.stringify(root).slice(1, -1);
    await writeFile(join(root, 'config.lock.toml'), template.replaceAll('__BRIDGE_RUNTIME__', escapedRoot).replaceAll('__CREDENTIAL_STORE__', credentialStore), { mode: 0o600, flag: 'wx' });
    return {
      root, cwd: join(root, 'cwd'), home: join(root, 'home'), lock: join(root, 'config.lock.toml'),
      async remove() { await rm(root, { recursive: true, force: true }); },
    };
  } catch { await rm(root, { recursive: true, force: true }); throw new BridgeError('PROCESS_FAILED'); }
}
export function isolatedArguments(lock) {
  return ['app-server', '--stdio', '-c', `debug.config_lockfile.load_path=${JSON.stringify(lock)}`,
    '-c', 'debug.config_lockfile.allow_codex_version_mismatch=false',
    '-c', 'debug.config_lockfile.save_fields_resolved_from_model_catalog=false'];
}
export async function verifyVersion(command, runtime) {
  try {
    const result = await exec(command, ['--version'], {
      cwd: runtime.cwd, env: { HOME: runtime.home, CODEX_HOME: join(runtime.root, 'auth-probe'), LANG: 'C.UTF-8' },
      shell: false, timeout: 3000, maxBuffer: 4096, windowsHide: true,
    });
    if (result.stdout.trim() !== `codex-cli ${CODEX_VERSION}`) throw new Error();
  } catch { throw new BridgeError('VERSION_UNSUPPORTED'); }
}
/** Called only after the user supplies a trusted executable. Never inspect credential files. */
export async function launchIsolated(executable, source = process.env, credentialStore = 'file') {
  if (process.platform !== 'darwin') throw new BridgeError('PLATFORM_UNSUPPORTED');
  const command = await executablePath(executable);
  const authHome = source.CODEX_HOME ?? (typeof source.HOME === 'string' ? join(source.HOME, '.codex') : undefined);
  if (typeof authHome !== 'string' || !isAbsolute(authHome)) throw new BridgeError('CONFIG_INVALID');
  try { await realpath(authHome); } catch { throw new BridgeError('CONFIG_INVALID'); }
  const runtime = await prepareRuntime(credentialStore);
  try {
    await verifyVersion(command, runtime);
    const env = { HOME: runtime.home, CODEX_HOME: authHome, LANG: 'C.UTF-8' };
    const client = new RpcProcess(command, isolatedArguments(runtime.lock), { cwd: runtime.cwd, env });
    const close = client.close.bind(client);
    let closing;
    client.close = () => closing ??= (async () => {
      try { await close(); } finally { await runtime.remove(); }
    })();
    return client;
  } catch (error) { await runtime.remove(); throw error instanceof BridgeError ? error : new BridgeError('PROCESS_FAILED'); }
}
