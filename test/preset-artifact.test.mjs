import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { buildPreset } from '../scripts/sync-preset.mjs';

const artifact = await readFile(new URL('../presets/codex-subscription.patch.yml', import.meta.url), 'utf8');
const lines = artifact.split('\n');
const childIds = lines.filter((line) => /^ {10}- id: /u.test(line)).map((line) => line.trim().slice('- id: '.length));
const manifest = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));

/** The compaction group, from its row to the next top-level child. */
function compactionGroup(lines) {
  const start = lines.indexOf('          - id: compaction');
  return lines.slice(start, lines.findIndex((line, index) => index > start && /^ {10}- id: /u.test(line)));
}

/** A minimal stand-in for the shipped preset that the generator can derive a row from. */
const source = [
  '# minimal stand-in for the shipped preset',
  '- insert:',
  '    - id: preset-standard',
  "      name: '@deepseek-ai/dsh-agent-preset'",
  '      config:',
  '        id: standard',
  '        order: 1',
  '        plugins:',
  '          - id: persona',
  "            name: '@deepseek-ai/dsh-persona'",
  '          - id: compaction',
  '            name: cordis:group',
  '            group: true',
  '            config:',
  '              - id: compaction-basic',
  "                name: '@deepseek-ai/dsh-compaction-basic'",
  '              - id: command-compact',
  "                name: '@deepseek-ai/dsh-command-compact'",
  '',
].join('\n');

test('the shipped preset is generated from the pinned version and inserted disabled', () => {
  assert.match(lines[0], /^# Generated by scripts\/sync-preset\.mjs from @deepseek-ai\/dsh-web-app@\d/u);
  assert.equal(lines.filter((line) => line === '- insert:').length, 1, 'one insert list');
  assert.equal(lines.filter((line) => line === '    - id: preset-codex-subscription').length, 1, 'one preset row');
  assert.equal(lines.filter((line) => line === '      disabled: true').length, 1, 'inserted disabled');
});

test('the shipped preset names the roster it owns', () => {
  assert.equal(lines.filter((line) => line === "      name: '@deepseek-ai/dsh-agent-preset'").length, 1);
  assert.equal(lines.filter((line) => line === '        id: codex-subscription').length, 1);
  assert.ok(lines.includes('        name: Codex subscription'), 'the roster needs a name');
  assert.ok(lines.some((line) => line.startsWith('        description: ')), 'the roster needs a description');
});

test('the shipped preset is ordered after the shipped presets', () => {
  assert.equal(lines.filter((line) => line === '        order: 9').length, 1, 'ordered after the shipped presets');
});

test('the shipped preset keeps the pinned 22-child composition', () => {
  assert.equal(childIds.length, 22, 'the pinned standard composition has 22 children');
  assert.equal(childIds[0], 'persona');
  assert.equal(childIds.at(-1), 'tool-plugin-market');
});

test('child ids stay printable', () => {
  assert.ok(childIds.every((id) => /^[a-z0-9-]+$/u.test(id)), 'child ids stay printable');
});

test('the compaction group keeps one engine and its isolated config', () => {
  const group = compactionGroup(lines);

  assert.ok(lines.indexOf('          - id: compaction') > 0, 'the compaction group is present');
  assert.deepEqual(group.filter((line) => /^ {14}- id: /u.test(line)).map((line) => line.trim()), [
    '- id: compaction-basic', '- id: command-compact', '- id: tool-result-pruner',
  ]);
  assert.ok(group.includes('            config:'), 'the group keeps its isolated config list');
  assert.ok(group.includes('              compaction: true'), 'the service stays isolated per preset');
  assert.equal(group.filter((line) => line === '                name: dsh-codex-subscription-bridge/compaction').length, 1);
});

test('the stock compaction engine is replaced, not shadowed', () => {
  assert.ok(!artifact.includes('@deepseek-ai/dsh-compaction-basic'), 'the stock engine is replaced, not shadowed');
});

test('platform conditions survive the copy verbatim', () => {
  assert.equal([...artifact.matchAll(/!!js/gu)].length, 2);
  assert.ok(artifact.includes("disabled: !!js process.platform === 'win32'"));
  assert.ok(artifact.includes("disabled: !!js process.platform !== 'win32'"));
});

test('the generator derives the row from a minimal source', () => {
  const built = buildPreset(source, '9.9.9');

  assert.ok(built.includes('# Generated by scripts/sync-preset.mjs from @deepseek-ai/dsh-web-app@9.9.9'));
  assert.ok(built.includes('    - id: preset-codex-subscription\n      name:'));
  assert.ok(built.includes('      disabled: true\n'));
  assert.ok(built.includes('        id: codex-subscription\n'));
  assert.ok(built.includes('                name: dsh-codex-subscription-bridge/compaction\n'));
  assert.ok(built.includes('          - id: persona'), 'children are preserved');
  assert.ok(!built.includes('preset-standard'));
});

test('the generator rejects drift', () => {
  assert.throws(() => buildPreset(source.replace("                name: '@deepseek-ai/dsh-compaction-basic'\n", ''), '9.9.9'), /compaction engine/u);
  assert.throws(() => buildPreset(source.replace('    - id: preset-standard\n', '    - id: preset-standard\n    - id: preset-standard\n'), '9.9.9'), /more than once/u);
  assert.throws(() => buildPreset('not a preset\n', '9.9.9'), /insert list/u);
});

test('the package lists the preset as its second bundle patch', () => {
  assert.deepEqual(manifest.dsh.bundle.patch, ['./cordis.patch.yml', './presets/codex-subscription.patch.yml']);
});

test('the package ships the presets directory', () => {
  assert.ok(manifest.files.includes('presets'), 'the artifact ships');
});

test('the package exports the compaction engine', () => {
  assert.equal(manifest.exports['./compaction'], './lib/compaction-engine.js');
});

test('the package defines the preset sync and check scripts', () => {
  assert.equal(manifest.scripts['preset:sync'], 'node scripts/sync-preset.mjs');
  assert.equal(manifest.scripts['preset:check'], 'node scripts/sync-preset.mjs --check');
});

test('every patch path the bundle names resolves through the package exports', () => {
  for (const patch of manifest.dsh.bundle.patch) assert.equal(manifest.exports[patch], patch, `${patch} is not exported`);
});
