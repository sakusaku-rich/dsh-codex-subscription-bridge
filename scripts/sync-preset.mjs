#!/usr/bin/env node
/**
 * Regenerate the opt-in agent preset that mirrors the shipped standard preset.
 *
 * The opt-in backend replaces one child of an agent preset's `compaction` group,
 * and a preset is a complete declaration, so the row has to restate every
 * sibling the Harness ships. Deriving that row from the pinned Harness keeps the
 * difference to a handful of lines, makes a Harness bump produce a reviewable
 * diff, and turns drift into a `--check` failure instead of a silent gap.
 *
 * The generated row is inserted DISABLED: installing this package must not add a
 * selectable preset to every profile. A profile enables it from the Plugins page,
 * which writes an id-keyed override into the profile patch.
 *
 * Usage:
 *   node scripts/sync-preset.mjs [--from <@deepseek-ai/dsh-web-app directory>]
 *   node scripts/sync-preset.mjs --check
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const harnessName = '@deepseek-ai/dsh-web-app';
const harnessVersion = '0.2.0-rc.2';
const sourcePreset = 'presets/standard.patch.yml';
const outputPath = join(repo, 'presets', 'codex-subscription.patch.yml');
const rowId = 'preset-codex-subscription';
const presetId = 'codex-subscription';
const presetName = 'Codex subscription';
const presetDescription = 'Standard tools, with Codex owning condensation for its own routes';
const engine = 'dsh-codex-subscription-bridge/compaction';
const shippedEngine = '@deepseek-ai/dsh-compaction-basic';
const presetOrder = 9;
const childIndent = 10;
const children = 19;

function count(text, pattern) {
  return [...text.matchAll(pattern)].length;
}

function replaceOnce(text, from, to, label) {
  const first = text.indexOf(from);
  if (first < 0) throw new Error(`The pinned preset no longer contains ${label}; review ${harnessName}@${harnessVersion}.`);
  if (text.indexOf(from, first + from.length) >= 0) throw new Error(`The pinned preset contains ${label} more than once; review the transformation.`);
  return text.slice(0, first) + to + text.slice(first + from.length);
}

/** Derive the opt-in preset row from the pinned standard preset text. */
export function buildPreset(source, version = harnessVersion) {
  const header = `# Generated by scripts/sync-preset.mjs from ${harnessName}@${version}\n`
    + `# ${sourcePreset}; do not edit by hand, run \`npm run preset:sync\`.\n`
    + '#\n'
    + '# Inserted DISABLED: enabling it from the Plugins page (or with a profile-patch\n'
    + '# override) mounts this bridge\'s compaction engine for codex-subscription routes\n'
    + '# while every other provider keeps the stock engine. Mirrors the shipped standard\n'
    + '# preset, so an edit saved from the Web editor overrides this row\'s `config.plugins`\n'
    + '# by id from the profile patch.\n';
  const body = source.slice(source.indexOf('- insert:'));
  if (!body.startsWith('- insert:')) throw new Error(`The pinned preset no longer starts with an insert list; review ${harnessName}@${harnessVersion}.`);
  let text = body;
  text = replaceOnce(text, '    - id: preset-standard\n', `    - id: ${rowId}\n`, 'the shipped preset row id');
  text = replaceOnce(text, "      name: '@deepseek-ai/dsh-agent-preset'\n",
    `      name: '@deepseek-ai/dsh-agent-preset'\n      disabled: true\n`, 'the preset module name');
  text = replaceOnce(text, '        id: standard\n',
    `        id: ${presetId}\n        name: ${presetName}\n        description: ${presetDescription}\n`, 'the preset config id');
  text = replaceOnce(text, '        order: 1\n', `        order: ${presetOrder}\n`, 'the preset order');
  text = replaceOnce(text, `                name: '${shippedEngine}'\n`, `                name: ${engine}\n`, 'the shipped compaction engine');
  const result = `${header}${text}`;
  const problems = [
    [count(result, new RegExp(`^ {4}- id: ${rowId}$`, 'gmu')) === 1, `exactly one ${rowId} row`],
    [count(result, new RegExp(`^ {6}disabled: true$`, 'gmu')) === 1, 'a disabled preset row'],
    [count(result, new RegExp(`^ {${childIndent}}- id: `, 'gmu')) === count(source, new RegExp(`^ {${childIndent}}- id: `, 'gmu')), 'every child plugin preserved'],
    [count(result, /!!js/gu) === count(source, /!!js/gu), 'every !!js condition preserved'],
    [count(result, new RegExp(`^ {16}name: ${engine.replace(/[.]/gu, '\\.')}$`, 'gmu')) === 1, `one ${engine} child`],
    [!result.includes(shippedEngine), 'the shipped engine replaced'],
  ].filter(([ok]) => !ok).map(([, label]) => label);
  if (problems.length > 0) throw new Error(`The generated preset failed its invariants: ${problems.join(', ')}.`);
  return result;
}

function sourceDirectory(argv) {
  const flag = argv.indexOf('--from');
  if (flag >= 0) {
    const value = argv[flag + 1];
    if (value === undefined || value.startsWith('--')) throw new Error('--from needs a directory.');
    return resolve(value);
  }
  return [join(repo, 'verification', 'runtime', 'node_modules', harnessName), join(repo, 'node_modules', harnessName)]
    .find(candidate => existsSync(join(candidate, sourcePreset)));
}

async function main(argv) {
  const check = argv.includes('--check');
  const directory = sourceDirectory(argv);
  if (directory === undefined) {
    throw new Error(`Install the pinned runtime first (npm --prefix verification/runtime ci) or pass --from <${harnessName} directory>.`);
  }
  const manifest = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
  if (manifest.name !== harnessName || manifest.version !== harnessVersion) {
    throw new Error(`Expected ${harnessName}@${harnessVersion}, found ${manifest.name}@${manifest.version}.`);
  }
  const source = await readFile(join(directory, sourcePreset), 'utf8');
  const generated = buildPreset(source, manifest.version);
  if (check) {
    const committed = await readFile(outputPath, 'utf8').catch(() => '');
    if (committed !== generated) throw new Error(`${outputPath} is stale; run npm run preset:sync and review the diff.`);
    console.log(`PRESET_OK (${harnessName}@${manifest.version}, ${children} child plugins, engine ${engine})`);
    return;
  }
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generated);
  console.log(`Wrote ${outputPath} from ${harnessName}@${manifest.version}.`);
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main(process.argv.slice(2));